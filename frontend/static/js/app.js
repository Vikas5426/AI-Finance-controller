function updateUserBadge() {
  const badgeTag = document.getElementById('header-user-role-tag');
  const emailTag = document.getElementById('header-user-email');
  const avatar = document.getElementById('header-avatar');
  const user = appState.currentUser;

  if (!user) {
    if (badgeTag) {
      badgeTag.textContent = 'Signed out';
      badgeTag.className = 'badge-min badge-gray';
    }
    if (emailTag) emailTag.textContent = '—';
    if (avatar) {
      avatar.innerHTML = `–<div class="avatar-online-dot"></div>`;
      avatar.setAttribute('title', 'Signed out');
    }
    return;
  }

  // Distinct role representation honoring Maker-Checker governance
  const ROLE_LABELS = {
    admin: ['Administrator · Full Access', 'badge-amber'],
    approver: ['Approver · Checker', 'badge-blue'],
    analyst: ['Analyst · Maker', 'badge-slate'],
    viewer: ['Viewer · Read Only', 'badge-slate']
  };
  const [label, cls] = ROLE_LABELS[user.role] || ['Administrator · Full Access', 'badge-amber'];

  if (badgeTag) {
    badgeTag.textContent = label;
    badgeTag.className = `badge-min ${cls}`;
  }
  if (emailTag) emailTag.textContent = user.email || '—';
  if (avatar) {
    const nameOrEmail = user.email || user.full_name || 'Admin';
    const initial = nameOrEmail[0].toUpperCase();
    avatar.innerHTML = `${initial}<div class="avatar-online-dot"></div>`;
    avatar.setAttribute('title', `${user.full_name || user.email} (${user.role}) — click to sign out`);
  }
}

async function authFetch(url, options = {}) {
  if (!appState.authToken) {
    // No session: block the call and ask for a credential rather than
    // silently signing in as a privileged user.
    showAuthGate('Your session has ended. Please sign in again.');
    throw new Error('Not authenticated. Please sign in.');
  }

  options.headers = options.headers || {};
  if (options.headers instanceof Headers) {
    options.headers.set('Authorization', `Bearer ${appState.authToken}`);
  } else {
    options.headers['Authorization'] = `Bearer ${appState.authToken}`;
  }

  const res = await fetch(url, options);
  if (res.status === 401) {
    // An expired or rejected token means re-authenticate as *this* user. The
    // previous behaviour re-logged in as the Approver, which silently escalated
    // an analyst's session to checker authority.
    clearSession();
    showAuthGate('Your session has expired. Please sign in again.');
  }
  return res;
}

