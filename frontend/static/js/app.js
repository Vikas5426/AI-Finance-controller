// UX-07: Source Kind Conflict Heuristic
function checkSourceMismatch(name, kind) {
  const n = (name || '').toLowerCase();
  const k = (kind || '').toUpperCase();
  if (n.includes('bank') && k.includes('GATEWAY')) {
    return `"${name}" was detected as Payment Gateway. Did you mean Bank Statement?`;
  }
  if (n.includes('gateway') && k.includes('BANK')) {
    return `"${name}" was detected as Bank Statement. Did you mean Payment Gateway?`;
  }
  if (n.includes('ledger') && (k.includes('GATEWAY') || k.includes('BANK'))) {
    return `"${name}" was detected as ${k === 'BANK' ? 'Bank Statement' : 'Payment Gateway'}. Did you mean General Ledger?`;
  }
  return null;
}

