async function runAgent(agentId) {
  selectAgent(agentId);
  const badgeEl = document.getElementById('agent-active-status-badge');
  const container = document.getElementById('agent-output-container');
  const streamEl = document.getElementById('agent-thought-stream');
  
  if (badgeEl) {
    badgeEl.textContent = 'Working...';
    badgeEl.className = 'badge-min badge-amber';
  }

  // Do not show fake pre-flight thought stream; hide until real backend confirmation
  if (streamEl) streamEl.style.display = 'none';

  if (container) {
    container.innerHTML = `
      <div style="display: flex; flex-direction: column; align-items: center; justify-content: center; padding: 4rem 1rem; gap: 0.75rem;">
        <div style="display: inline-block; width: 28px; height: 28px; border: 3px solid var(--border-medium); border-top-color: var(--accent-cyan); border-radius: 50%; animation: spin 0.8s linear infinite;"></div>
        <div style="font-size: 0.85rem; font-weight: 600; color: var(--text-primary);">Agent ${agentId}: ${AGENT_META[agentId]?.name} Working...</div>
        <div style="font-size: 0.75rem; color: var(--text-muted);">Executing reasoning with deterministic arithmetic verification.</div>
      </div>
    `;
  }

  try {
    let endpoint = `${API_BASE}/agents/rca`;
    let body = {};
    if (agentId === 9) {
      endpoint = `${API_BASE}/agents/investigate`;
      const selectEl = document.getElementById('agent-9-target-select');
      const targetVal = selectEl?.value || '';

      const matchedExc = (appState.allExceptions || []).find(e => e.id === targetVal);
      if (matchedExc) {
        const primTxn = (appState.allTransactions || []).find(t => t.id === matchedExc.primary_txn_id) || null;
        const countTxn = (appState.allTransactions || []).find(t => t.id === matchedExc.counterpart_txn_id) || null;
        body = {
          exception_id: matchedExc.id,
          exception_type: matchedExc.exception_type || 'MANUAL_REVIEW',
          impact_minor: matchedExc.impact_minor || 0,
          primary_txn: primTxn,
          counterpart_txn: countTxn,
          severity: matchedExc.severity || 'MEDIUM'
        };
      } else {
        throw new Error('Select a real exception from the active batch to investigate. Run a reconciliation first if the list is empty.');
      }
    } else if (agentId === 10) {
      endpoint = `${API_BASE}/agents/rca`;
      body = { batch_id: appState.batchId };
    } else if (agentId === 11) {
      endpoint = `${API_BASE}/agents/insights`;
      body = { batch_id: appState.batchId };
    } else if (agentId === 12) {
      endpoint = `${API_BASE}/agents/audit-explain`;
      body = { batch_id: appState.batchId };
    } else if (agentId === 13) {
      endpoint = `${API_BASE}/agents/generate-report`;
      body = { batch_id: appState.batchId };
    }

    const res = await authFetch(endpoint, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(body)
    });

    if (!res.ok) {
      let detail = '';
      try {
        const errBody = await res.json();
        detail = errBody?.detail || errBody?.message || '';
      } catch (_) {
        try { detail = (await res.text()).slice(0, 300); } catch (_) { /* body already consumed */ }
      }
      const err = new Error(detail ? `HTTP ${res.status} — ${detail}` : `HTTP ${res.status} ${res.statusText || ''}`.trim());
      err.status = res.status;
      throw err;
    }

    const data = await res.json();
    const isFallback = Boolean(data.fallback_used || data?.telemetry?.provider === 'DETERMINISTIC_REASONER');

    // Real backend confirmation - paint verified steps
    renderThoughtStreamSteps(5);

    appState.agentResults[agentId] = data;
    if (badgeEl) {
      if (isFallback) {
        badgeEl.textContent = 'Completed (deterministic fallback — no AI)';
        badgeEl.className = 'badge-min badge-amber';
      } else {
        badgeEl.textContent = 'Completed (Verified)';
        badgeEl.className = 'badge-min badge-green';
      }
    }
    renderAgentActiveOutput();
    fetchAgentTelemetry();
    showToast(`Agent ${agentId} (${AGENT_META[agentId]?.name}) completed successfully.`, 'success');
  } catch (err) {
    console.error(`Agent ${agentId} failed:`, err);
    appState.agentResults[agentId] = { error: true, status: err.status || 500 };
    renderThoughtStreamSteps(2, 2);
    if (badgeEl) {
      badgeEl.textContent = `Failed (HTTP ${err.status || 500})`;
      badgeEl.className = 'badge-min badge-coral';
    }
    if (container) {
      container.innerHTML = renderAgentError(agentId, err);
    }
    showToast(`Agent ${agentId} failed: ${err?.message || 'unknown error'}`, 'error');
    fetchAgentTelemetry();
  }
}

async function runAllAgents() {
  const btn = document.getElementById('btn-agents-run-all');
  const oldText = btn ? btn.textContent : '';
  if (btn) {
    btn.disabled = true;
    btn.classList.add('btn-loading');
    btn.setAttribute('aria-busy', 'true');
    btn.textContent = 'Executing Reasoning Suite...';
  }

  showToast('Executing 5-agent reasoning suite in sequence...', 'info');

  try {
    const res = await authFetch(`${API_BASE}/agents/run-all`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ batch_id: appState.batchId })
    });

    if (!res.ok) {
      let detail = '';
      try {
        const errBody = await res.json();
        detail = errBody?.detail || errBody?.message || '';
      } catch (_) {
        try { detail = (await res.text()).slice(0, 300); } catch (_) { /* body already consumed */ }
      }
      throw new Error(detail ? `HTTP ${res.status} — ${detail}` : `HTTP ${res.status} ${res.statusText || ''}`.trim());
    }

    const data = await res.json();
    const produced = {
      10: data.root_cause_analysis,
      11: data.financial_insights,
      12: data.audit_explanation,
      13: data.controller_report
    };
    Object.entries(produced).forEach(([id, result]) => {
      if (result) appState.agentResults[id] = result;
    });

    // Also trigger agent 9 (handles and reports its own failure).
    await runAgent(9);

    const batchIds = Object.keys(produced);
    const ok = batchIds.filter((id) => !!produced[id]);
    const missing = batchIds.filter((id) => !produced[id]);
    const fallbacks = ok.filter((id) => produced[id]?.telemetry?.provider === 'DETERMINISTIC_REASONER');
    const agent9Ok = !!appState.agentResults[9];
    const totalOk = ok.length + (agent9Ok ? 1 : 0);

    selectAgent(13); // Show executive report by default

    // Report what actually came back. Claiming "all 5 succeeded with zero
    // hallucinations" is unverifiable from the client and hides partial failures.
    if (totalOk === 5 && fallbacks.length === 0) {
      showToast('All 5 reasoning agents completed and passed the deterministic verifier.', 'success');
    } else if (totalOk === 0) {
      showToast('Run All finished but no agent returned an analysis. Check the backend logs.', 'error');
    } else {
      const parts = [`${totalOk}/5 agents returned an analysis`];
      if (fallbacks.length) parts.push(`${fallbacks.length} used the deterministic fallback (no LLM)`);
      if (missing.length) parts.push(`no output for agent ${missing.join(', ')}`);
      if (!agent9Ok) parts.push('agent 9 failed');
      showToast(`${parts.join('; ')}.`, 'warn');
    }
  } catch (err) {
    console.error('Run all error:', err);
    // Reflect the failure on the panel the user is looking at, not just in a toast.
    const badgeEl = document.getElementById('agent-active-status-badge');
    if (badgeEl) {
      badgeEl.textContent = 'Failed';
      badgeEl.className = 'badge-min badge-coral';
    }
    showToast(`Run All failed: ${err?.message || 'unknown error'}. No agent output was produced.`, 'error');
  } finally {
    if (btn) {
      btn.innerHTML = `<svg width="13" height="13" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><polygon points="5 3 19 12 5 21 5 3"/></svg> Run All Batch Agents (1-Click)`;
    }
  }
}

