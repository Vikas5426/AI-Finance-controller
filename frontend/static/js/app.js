function showAuthGate(message) {
  const gate = document.getElementById('auth-gate');
  const errEl = document.getElementById('auth-error');
  if (errEl) {
    if (message) {
      errEl.textContent = message;
      errEl.hidden = false;
    } else {
      errEl.textContent = '';
      errEl.hidden = true;
    }
  }
  if (gate) {
    gate.hidden = false;
    document.body.style.overflow = 'hidden';
    document.getElementById('auth-email')?.focus();
  }
}

function hideAuthGate() {
  const gate = document.getElementById('auth-gate');
  if (gate) gate.hidden = true;
  document.body.style.overflow = '';
  const pw = document.getElementById('auth-password');
  if (pw) pw.value = '';   // never leave a password sitting in the DOM
}

/**
 * Resolves true only when a valid session exists. Never mints one on the
 * user's behalf: an automatic sign-in as the Approver handed checker authority
 * (which is what releases money) to anyone who opened the page.
 */
async function ensureAuthenticated() {
  const isValid = await checkAuthSession();
  if (isValid) {
    hideAuthGate();
    return true;
  }
  showAuthGate();
  return false;
}

function signOut() {
  clearSession();
  showAuthGate();
  showToast('Signed out.', 'info');
}

function initAuthGate() {
  const form = document.getElementById('auth-form');
  const submitBtn = document.getElementById('auth-submit');
  if (!form) return;

  form.addEventListener('submit', async (e) => {
    e.preventDefault();
    const isSignUp = window.currentAuthTab === 'signup';
    const fullName = document.getElementById('auth-fullname')?.value.trim() || '';
    const email = document.getElementById('auth-email')?.value.trim() || '';
    const password = document.getElementById('auth-password')?.value || '';
    const role = document.getElementById('auth-role')?.value || 'admin';
    const errEl = document.getElementById('auth-error');

    if (submitBtn) {
      submitBtn.disabled = true;
      submitBtn.textContent = isSignUp ? 'Creating account...' : 'Signing in...';
    }
    if (errEl) errEl.hidden = true;

    const result = isSignUp 
      ? await registerUser(fullName, email, password, role)
      : await loginUser(email, password);

    if (submitBtn) {
      submitBtn.disabled = false;
      submitBtn.textContent = isSignUp ? 'Create account' : 'Sign in';
    }

    if (result.ok) {
      hideAuthGate();
      showToast(isSignUp ? `Account created! Welcome, ${appState.currentUser?.full_name || email}.` : `Signed in as ${appState.currentUser?.full_name || email}.`, 'success');
      updateOverviewVisibility();
      fetchInitialData();
    } else if (errEl) {
      errEl.textContent = result.error;
      errEl.hidden = false;
    }
  });

  // Password visibility toggle
  const pwToggleBtn = document.getElementById('auth-pw-toggle');
  const pwInput = document.getElementById('auth-password');
  const eyeIcon = document.getElementById('auth-pw-icon-eye');
  const eyeOffIcon = document.getElementById('auth-pw-icon-eye-off');

  if (pwToggleBtn && pwInput) {
    pwToggleBtn.addEventListener('click', () => {
      const isPw = pwInput.type === 'password';
      pwInput.type = isPw ? 'text' : 'password';
      if (eyeIcon) eyeIcon.style.display = isPw ? 'none' : 'block';
      if (eyeOffIcon) eyeOffIcon.style.display = isPw ? 'block' : 'none';
      pwToggleBtn.title = isPw ? 'Hide password' : 'Show password';
    });
  }
}

