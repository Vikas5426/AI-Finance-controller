function filterTxns(cat) {
  const all = appState.allTransactions;
  if (!all.length) return [];

  switch (cat) {
    case 'matched': return all.filter(t => isTxnMatched(t));
    case 'cutoff': return all.filter(t => (t.match_status === 'NEEDS_REVIEW' || (t.description_raw && t.description_raw.includes('CUTOFF')) || (t.occurred_at && (t.occurred_at.includes('2026-03-31') || t.occurred_at.includes('2026-08-31')))));
    case 'fee': return all.filter(t => t.fee_minor > 0 || (t.description_raw && t.description_raw.includes('MDR')));
    case 'missing': return all.filter(t => getTxnSourceKind(t) === 'GATEWAY' && !isTxnMatched(t));
    case 'unmatched': default: return all.filter(t => !isTxnMatched(t));
  }
}

