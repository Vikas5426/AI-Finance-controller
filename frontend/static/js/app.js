function processFiles(files) {
  if (!files.length) return;

  files.forEach(file => {
    const fName = file.name.toLowerCase();
    let streamType = 'GATEWAY';
    if (fName.includes('bank') || fName.includes('stmt')) streamType = 'BANK';
    else if (fName.includes('ledger') || fName.includes('gl') || fName.includes('erp')) streamType = 'LEDGER';
    else if (fName.includes('settl')) streamType = 'SETTLEMENT';

    const fileEntry = {
      id: `file_${Date.now()}_${Math.random().toString(36).substr(2, 4)}`,
      name: file.name,
      size: formatBytes(file.size),
      type: streamType,
      fileObj: file,
      rowCount: 0
    };

    const reader = new FileReader();
    reader.onload = (e) => {
      const text = e.target?.result || '';
      const lines = String(text).split('\n').map(l => l.trim()).filter(l => l.length > 0);
      fileEntry.rowCount = Math.max(0, lines.length - 1);
      refreshWizardGates();
    };
    reader.readAsText(file.slice(0, 1024 * 1024));

    appState.uploadedFiles.push(fileEntry);
  });

  renderUploadedFilesList();
  renderSidebarActiveFeeds();
  refreshWizardGates();
  showToast(`${files.length} file(s) configured.`, 'success');
}

