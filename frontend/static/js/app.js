// AUTHENTICATION & SECURE SESSION MANAGEMENT
// ==============================================================================
//
// There are deliberately no credentials in this file. Shipping a password in
// client JavaScript publishes it to every visitor: it is readable in devtools,
// in the served asset, and in any cached copy. The app therefore starts signed
// out and requires a real credential before it will load any financial data.

async function checkAuthSession() {
  if (!appState.authToken) return false;
  try {
    const res = await fetch(`${API_BASE}/auth/me`, {
      headers: { 'Authorization': `Bearer ${appState.authToken}` }
    });
    if (res.ok) {
      const data = await res.json();
      // /auth/me returns claims only; keep the richer profile from login if we
      // already have one for the same user.
      const stored = appState.currentUser;
      appState.currentUser = (stored && stored.user_id === data.user_id)
        ? { ...data, ...stored }
        : data;
      localStorage.setItem('fin_user_profile', JSON.stringify(appState.currentUser));
      updateUserBadge();
      return true;
    }
    if (res.status === 401) clearSession();
  } catch (e) {
    // Network failure is not the same as an invalid session; keep the token.
    console.warn('Session check could not reach the server:', e);
  }
  return false;
}

function clearSession() {
  appState.authToken = null;
  appState.currentUser = null;
  localStorage.removeItem('fin_jwt_token');
  localStorage.removeItem('fin_user_profile');
  updateUserBadge();
}

/**
 * Exchanges a credential for a JWT. Returns {ok, error} so the caller can show
 * the server's actual reason instead of guessing.
 */
async function loginUser(email, password) {
  if (!email || !password) {
    return { ok: false, error: 'Email and password are both required.' };
  }
  try {
    const res = await fetch(`${API_BASE}/auth/login`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ email, password })
    });

    if (!res.ok) {
      let detail = '';
      try {
        const body = await res.json();
        detail = body?.detail || body?.message || '';
      } catch (_) { /* non-JSON error body */ }
      return {
        ok: false,
        error: detail || (res.status === 401
          ? 'Invalid email or password.'
          : `Sign-in failed (HTTP ${res.status}).`)
      };
    }

    const data = await res.json();
    appState.authToken = data.access_token;
    appState.currentUser = {
      user_id: data.user_id,
      email: data.email,
      full_name: data.full_name,
      role: data.role,
      org_id: data.org_id
    };
    localStorage.setItem('fin_jwt_token', data.access_token);
    localStorage.setItem('fin_user_profile', JSON.stringify(appState.currentUser));
    updateUserBadge();
    return { ok: true };
  } catch (err) {
    console.error('Authentication error:', err);
    return { ok: false, error: 'Could not reach the authentication service. Is the backend running?' };
  }
}

