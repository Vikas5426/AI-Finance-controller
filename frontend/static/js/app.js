// UX-06: Honest AI Involvement Badge Helper
function renderAIBadge(engineType, verifierPassed = true) {
  if (!engineType || engineType === 'DETERMINISTIC_REASONER' || engineType === 'RULES') {
    return `<span class="badge-min badge-rules-based" title="Processed deterministically via SOP Rules Engine">Rules-based</span>`;
  }
  if (engineType === 'FALLBACK' || engineType === 'UNAVAILABLE') {
    return `<span class="badge-min badge-ai-fallback" title="AI inference was unavailable — deterministic fallback used">AI unavailable — rules used</span>`;
  }
  if (verifierPassed) {
    return `<span class="badge-min badge-ai-reasoned" title="Inference generated by LLM and mathematically verified to the paise">AI-reasoned</span>`;
  }
  return `<span class="badge-min badge-ai-fallback" title="AI reasoning generated without mathematical verification pass">AI unverified</span>`;
}

