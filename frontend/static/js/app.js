function renderClusterHistogram() {
  const container = document.getElementById('cluster-histogram-bars');
  if (!container) return;

  const labelRow = document.getElementById('cluster-histogram-labels');
  if (labelRow) labelRow.style.display = 'none';

  const badgeTotal = document.getElementById('badge-total-windows');
  const badgeHealthy = document.getElementById('badge-healthy-windows');
  const badgeWarm = document.getElementById('badge-warm-windows');
  const badgeCrit = document.getElementById('badge-crit-windows');

  let windows = (appState.batchReport && appState.batchReport.windows) ? [...appState.batchReport.windows] : [];

  // If batchReport.windows is absent but transactions exist in appState, chunk into 24-record windows dynamically
  if (!windows.length && appState.allTransactions && appState.allTransactions.length > 0) {
    const chunkSize = 24;
    const txns = appState.allTransactions;
    const excs = appState.allExceptions || [];
    const excIdSet = new Set(excs.map(e => e.primary_txn_id).filter(Boolean));

    for (let i = 0; i < txns.length; i += chunkSize) {
      const chunk = txns.slice(i, i + chunkSize);
      const chunkExcCount = chunk.filter(t => excIdSet.has(t.id)).length;
      const chunkMatched = chunk.length - chunkExcCount;
      windows.push({
        window_index: Math.floor(i / chunkSize) + 1,
        window_id: `WIN-${String(Math.floor(i / chunkSize) + 1).padStart(2, '0')}`,
        records_count: chunk.length,
        start_index: i,
        end_index: i + chunk.length,
        status: 'COMPLETED',
        exact_matches: chunkMatched,
        contextual_matches: 0,
        ai_investigated: 0,
        exceptions_count: chunkExcCount
      });
    }
  }

  if (!windows.length) {
    container.innerHTML = [1, 2, 3].map(num => `
      <div class="win-skeleton-card">
        <span class="win-skeleton-tag">WIN-0${num}</span>
        <span class="win-skeleton-sub">Awaiting Stream Ingest</span>
      </div>
    `).join('');
    if (badgeTotal) badgeTotal.textContent = '0 Windows';
    if (badgeWarm) badgeWarm.textContent = '0 Warnings';
    if (badgeCrit) badgeCrit.textContent = '0 Held';
    if (badgeHealthy) badgeHealthy.style.display = 'none';
    return;
  }

  // Render each window card with rich micro-metrics and multi-segment health telemetry
  container.innerHTML = windows.map((w, i) => {
    const wid = w.window_id || `WIN-${String(i + 1).padStart(2, '0')}`;
    const records = w.records_count || 0;
    const exact = w.exact_matches || 0;
    const ctx = w.contextual_matches || 0;
    const excs = w.exceptions_count || 0;
    const matched = exact + ctx;

    const startIdx = w.start_index !== undefined ? w.start_index + 1 : (i * 24 + 1);
    const endIdx = w.end_index !== undefined ? w.end_index : (startIdx + records - 1);
    const rangeLabel = records > 0 ? `Rec #${startIdx}–${endIdx}` : 'Idle';

    const matchRate = records > 0 ? (matched / records) * 100 : 100;
    const healthPct = Math.round(matchRate);

    let statusCls = 'status-healthy';
    let pillCls = 'pill-healthy';
    let pillText = `${healthPct}% Match`;

    if (records === 0) {
      statusCls = 'status-healthy';
      pillCls = 'pill-healthy';
      pillText = '100% Ingested';
    } else if (matchRate >= 90 && excs === 0) {
      statusCls = 'status-healthy';
      pillCls = 'pill-healthy';
      pillText = `${healthPct}% Match`;
    } else if (matchRate >= 50 || excs <= records * 0.3) {
      statusCls = 'status-warning';
      pillCls = 'pill-warning';
      pillText = `${healthPct}% Match`;
    } else {
      statusCls = 'status-critical';
      pillCls = 'pill-critical';
      pillText = `${healthPct}% Match`;
    }

    const exactPct = records > 0 ? Math.min(100, Math.round((exact / records) * 100)) : 0;
    const ctxPct = records > 0 ? Math.min(100 - exactPct, Math.round((ctx / records) * 100)) : 0;
    const heldPct = records > 0 ? Math.min(100 - exactPct - ctxPct, Math.round((excs / records) * 100)) : (records > 0 ? 100 - exactPct - ctxPct : 0);

    const execTime = (w.completed_at && w.started_at)
      ? `${Math.max(1, Math.round(new Date(w.completed_at) - new Date(w.started_at)))}ms exec`
      : '⚡ 24-Record Chunk';

    const tooltip = `${wid}: ${records} Records (${rangeLabel}) | Matched: ${matched} (${exact} exact, ${ctx} contextual) | Held Exceptions: ${excs} | Health: ${healthPct}%`;

    return `
      <div class="window-chunk-card ${statusCls}" title="${escapeHtml(tooltip)}">
        <div class="win-card-header">
          <div class="win-title-wrap">
            <span class="win-id-tag">${escapeHtml(wid)}</span>
            <span class="win-range-lbl">${rangeLabel}</span>
          </div>
          <span class="win-health-pill ${pillCls}">
            <span class="win-dot"></span>
            ${pillText}
          </span>
        </div>

        <div class="win-progress-track" title="Exact: ${exact} (${exactPct}%) | Contextual: ${ctx} (${ctxPct}%) | Held: ${excs} (${heldPct}%)">
          <div class="win-segment seg-exact" style="width: ${exactPct}%;"></div>
          <div class="win-segment seg-ctx" style="width: ${ctxPct}%;"></div>
          <div class="win-segment seg-held" style="width: ${heldPct}%;"></div>
        </div>

        <div class="win-metrics-grid">
          <div class="win-metric-item">
            <span class="win-metric-lbl">Total</span>
            <span class="win-metric-val">${records}</span>
          </div>
          <div class="win-metric-item">
            <span class="win-metric-lbl">Matched</span>
            <span class="win-metric-val val-green">${matched}</span>
          </div>
          <div class="win-metric-item">
            <span class="win-metric-lbl">Held</span>
            <span class="win-metric-val ${excs > 0 ? 'val-coral' : 'val-green'}">${excs}</span>
          </div>
        </div>

        <div class="win-card-footer">
          <span class="win-time-tag">${execTime}</span>
          <span class="win-status-text" style="color: ${excs > 0 ? 'var(--accent-coral)' : 'var(--accent-emerald)'};">
            ${excs > 0 ? `${excs} Held back` : 'All Reconciled ✓'}
          </span>
        </div>
      </div>
    `;
  }).join('');

  // Synchronize summary header badges
  const healthyCount = windows.filter(w => {
    const rec = w.records_count || 0;
    const exc = w.exceptions_count || 0;
    return rec > 0 && exc === 0;
  }).length;

  const warmCount = windows.filter(w => {
    const rec = w.records_count || 0;
    const exc = w.exceptions_count || 0;
    return rec > 0 && exc > 0 && exc <= rec * 0.3;
  }).length;

  const totalHeldInWindows = windows.reduce((acc, w) => acc + (w.exceptions_count || 0), 0);

  if (badgeTotal) badgeTotal.textContent = `${windows.length} Window${windows.length === 1 ? '' : 's'}`;
  if (badgeHealthy) {
    badgeHealthy.textContent = `${healthyCount} Optimal`;
    badgeHealthy.style.display = healthyCount > 0 ? 'inline-block' : 'none';
  }
  if (badgeWarm) {
    badgeWarm.textContent = `${warmCount} Warning${warmCount === 1 ? '' : 's'}`;
  }
  if (badgeCrit) {
    badgeCrit.textContent = `${totalHeldInWindows} Held`;
  }
}

