function renderBasicMarkdown(text) {
  if (!text) return '';

  const lines = text.split('\n');
  const output = [];
  let inTable = false;
  let tableRows = [];
  let inList = false;
  let listTag = 'ul';

  function flushTable() {
    if (!tableRows.length) return;
    let tableHtml = '<div style="overflow-x: auto; margin: 1rem 0;"><table style="width: 100%; border-collapse: collapse; font-size: 0.8rem; background: var(--bg-surface); border: 1px solid var(--border-subtle); border-radius: 6px;">';
    
    // Check if 2nd row is a separator row (| :--- | ---: | etc.)
    let startIdx = 0;
    if (tableRows.length > 1 && /^\|?[\s\-:]+(\|[\s\-:]+)+\|?$/.test(tableRows[1].trim())) {
      // Header row
      const headers = tableRows[0].split('|').map(c => c.trim()).filter((c, i, a) => !(i === 0 && c === '') && !(i === a.length - 1 && c === ''));
      tableHtml += '<thead><tr style="background: var(--bg-card); border-bottom: 2px solid var(--border-subtle);">';
      headers.forEach(h => {
        tableHtml += `<th style="padding: 0.6rem 0.85rem; text-align: left; font-weight: 700; color: var(--text-primary); border-right: 1px solid var(--border-subtle);">${formatInline(h)}</th>`;
      });
      tableHtml += '</tr></thead><tbody>';
      startIdx = 2;
    } else {
      tableHtml += '<tbody>';
    }

    for (let r = startIdx; r < tableRows.length; r++) {
      const cells = tableRows[r].split('|').map(c => c.trim()).filter((c, i, a) => !(i === 0 && c === '') && !(i === a.length - 1 && c === ''));
      if (!cells.length) continue;
      tableHtml += `<tr style="border-bottom: 1px solid var(--border-subtle); ${r % 2 === 1 ? 'background: rgba(255,255,255,0.015);' : ''}">`;
      cells.forEach(c => {
        tableHtml += `<td style="padding: 0.55rem 0.85rem; color: var(--text-secondary); border-right: 1px solid var(--border-subtle);">${formatInline(c)}</td>`;
      });
      tableHtml += '</tr>';
    }

    tableHtml += '</tbody></table></div>';
    output.push(tableHtml);
    tableRows = [];
    inTable = false;
  }

  function flushList() {
    if (inList) {
      output.push(`</${listTag}>`);
      inList = false;
      listTag = 'ul';
    }
  }

  function formatInline(str) {
    if (!str) return '';
    // Upfront HTML escaping to neutralize XSS tags and script injection (F-24)
    const sanitized = String(str)
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;')
      .replace(/'/g, '&#039;');

    return sanitized
      .replace(/\*\*(.*?)\*\*/g, '<strong style="color: var(--text-primary); font-weight: 700;">$1</strong>')
      .replace(/\*(.*?)\*/g, '<em style="color: var(--text-secondary);">$1</em>')
      .replace(/`([^`]+)`/g, '<code style="background: var(--bg-surface); border: 1px solid var(--border-subtle); padding: 0.15rem 0.4rem; border-radius: 4px; font-family: var(--font-mono); font-size: 0.78rem; color: var(--accent-cyan);">$1</code>');
  }

  for (let i = 0; i < lines.length; i++) {
    const rawLine = lines[i];
    const trimmed = rawLine.trim();

    // Table line
    if (trimmed.startsWith('|') && trimmed.endsWith('|') && trimmed.includes('|')) {
      flushList();
      inTable = true;
      tableRows.push(trimmed);
      continue;
    } else if (inTable) {
      flushTable();
    }

    // Blank line
    if (!trimmed) {
      flushList();
      output.push('<div style="height: 0.4rem;"></div>');
      continue;
    }

    // Horizontal Rule
    if (/^(\-{3,}|\*{3,}|_{3,})$/.test(trimmed)) {
      flushList();
      output.push('<hr style="border: none; border-top: 1px solid var(--border-subtle); margin: 1.25rem 0;" />');
      continue;
    }

    // Headings
    if (trimmed.startsWith('# ')) {
      flushList();
      output.push(`<h2 style="font-size: 1.25rem; font-weight: 800; color: var(--text-primary); margin: 1.25rem 0 0.5rem 0; border-bottom: 1px solid var(--border-subtle); padding-bottom: 0.4rem;">${formatInline(trimmed.slice(2))}</h2>`);
      continue;
    }
    if (trimmed.startsWith('## ')) {
      flushList();
      output.push(`<h3 style="font-size: 1.05rem; font-weight: 700; color: var(--accent-cyan); margin: 1.1rem 0 0.4rem 0;">${formatInline(trimmed.slice(3))}</h3>`);
      continue;
    }
    if (trimmed.startsWith('### ')) {
      flushList();
      output.push(`<h4 style="font-size: 0.95rem; font-weight: 700; color: var(--text-primary); margin: 0.9rem 0 0.35rem 0;">${formatInline(trimmed.slice(4))}</h4>`);
      continue;
    }
    if (trimmed.startsWith('#### ')) {
      flushList();
      output.push(`<h5 style="font-size: 0.88rem; font-weight: 700; color: var(--accent-amber); margin: 0.75rem 0 0.3rem 0;">${formatInline(trimmed.slice(5))}</h5>`);
      continue;
    }
    if (trimmed.startsWith('##### ')) {
      flushList();
      output.push(`<h6 style="font-size: 0.82rem; font-weight: 700; color: var(--text-secondary); margin: 0.6rem 0 0.25rem 0;">${formatInline(trimmed.slice(6))}</h6>`);
      continue;
    }

    // Blockquotes
    if (trimmed.startsWith('> ')) {
      flushList();
      output.push(`<blockquote style="border-left: 3px solid var(--accent-cyan); padding: 0.6rem 1rem; background: var(--bg-surface); margin: 0.75rem 0; border-radius: 0 6px 6px 0; color: var(--text-secondary); line-height: 1.5;">${formatInline(trimmed.slice(2))}</blockquote>`);
      continue;
    }

    // Task Checklist items
    if (/^[-*]\s+\[([ xX])\]\s+(.*)$/.test(trimmed)) {
      if (!inList) {
        output.push('<ul style="list-style: none; padding-left: 0; margin: 0.5rem 0;">');
        inList = true;
        listTag = 'ul';
      }
      const match = trimmed.match(/^[-*]\s+\[([ xX])\]\s+(.*)$/);
      const isChecked = match[1].toLowerCase() === 'x';
      const itemText = match[2];
      output.push(`
        <li style="margin-bottom: 0.4rem; display: flex; align-items: baseline; gap: 0.5rem;">
          <span style="color: ${isChecked ? 'var(--accent-emerald)' : 'var(--text-muted)'}; font-size: 0.95rem; font-weight: 700;">${isChecked ? '☑' : '☐'}</span>
          <span style="color: ${isChecked ? 'var(--text-primary)' : 'var(--text-secondary)'}; ${isChecked ? 'text-decoration: none;' : ''}">${formatInline(itemText)}</span>
        </li>
      `);
      continue;
    }

    // Unordered List Items
    if (/^[-*]\s+(.*)$/.test(trimmed)) {
      if (!inList) {
        output.push('<ul style="padding-left: 1.25rem; margin: 0.5rem 0;">');
        inList = true;
        listTag = 'ul';
      }
      const match = trimmed.match(/^[-*]\s+(.*)$/);
      output.push(`<li style="margin-bottom: 0.3rem; color: var(--text-secondary);">${formatInline(match[1])}</li>`);
      continue;
    }

    // Numbered List Items
    if (/^\d+\.\s+(.*)$/.test(trimmed)) {
      if (!inList) {
        output.push('<ol style="padding-left: 1.25rem; margin: 0.5rem 0;">');
        inList = true;
        listTag = 'ol';
      }
      const match = trimmed.match(/^\d+\.\s+(.*)$/);
      output.push(`<li style="margin-bottom: 0.35rem; color: var(--text-secondary);">${formatInline(match[1])}</li>`);
      continue;
    }

    // Regular paragraph
    flushList();
    output.push(`<p style="margin: 0.4rem 0; color: var(--text-secondary); line-height: 1.6;">${formatInline(trimmed)}</p>`);
  }

  if (inTable) flushTable();
  flushList();

  return output.join('\n');
}

